-- Λύση: μια ατομική «κράτηση» πάνω στο ήδη υπάρχον single-row live_trading_state —
-- ένα γρήγορο, ατομικό UPDATE statement (χωρίς ανάγκη ρητής transaction) σειριοποιεί
-- σωστά ταυτόχρονες απόπειρες, ό,τι κι αν δείχνει το (ενδεχομένως μπαγιάτικο) real
-- balance που κουβαλάει ο κάθε caller.
