-- Πραγματικό ρίσκο εντοπίστηκε 2026-09-15, πριν προλάβει να συμβεί στην πράξη: το
-- attemptLiveEntry ελέγχει το ΠΡΑΓΜΑΤΙΚΟ, on-chain balance πριν από κάθε live buy — αλλά
-- αν ΔΥΟ σήματα (διαφορετικά tokens) φτάσουν μέσα σε λίγα δευτερόλεπτα το ένα από το
-- άλλο, και τα δύο θα δουν το ΙΔΙΟ, ακόμα-αναλλοίωτο balance (το πρώτο swap δεν έχει
